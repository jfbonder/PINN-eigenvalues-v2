"""Write experiments/plap/tables.tex from experiments/results/plap_summary.json (run analyze first)."""
import json
from pathlib import Path
HERE = Path(__file__).resolve().parent
S = json.load(open(HERE.parent / "results" / "plap_summary.json"))
refs = json.load(open(HERE.parent / "results" / "plap_refs.json"))
pc = lambda x: "--" if x is None else f"${100*x:+.2f}$"
SYM = {"radial shooting (1st eigenvalue)": "radial, positive [shooting]",
       "FEM half disk (1 nodal diameter); Horak 18.395": "1 nodal diameter [FEM half disk; 18.395 in \\cite{HJ11}]",
       "FEM sector pi/2 (2 nodal diameters)": "2 nodal diameters [FEM sector $\\pi/2$]",
       "radial shooting, 1 nodal circle": "radial, 1 nodal circle [shooting]",
       "FEM sector pi/3 (3 nodal diameters)": "3 nodal diameters [FEM sector $\\pi/3$]",
       "FEM square (1st eigenvalue); Horak 5.4952": "positive [FEM; 5.4952 in \\cite{HJ11}]",
       "FEM half square, diagonal nodal line; Horak 15.144": "diagonal nodal line [FEM triangle; 15.144 in \\cite{HJ11}]",
       "FEM rectangle 1x2 (midline nodal line)": "midline nodal line [FEM rectangle]",
       "FEM [0,1]^2 = 2^p E1 (2x2 cells)": "$2\\times2$ cells [$2^{p}E_1$]",
       "scaled FEM triangle (both diagonals nodal), 2^{p/2} x 15.1429": "both diagonals nodal [$2^{p/2}\\times$ FEM triangle]",
       "FEM strip 2/3 x 2 (3 strips)": "3 strips [FEM]",
       "FEM axisymmetric half ball (nodal plane)": "1 nodal plane [axisymmetric FEM half ball]"}
out = []
out.append(r"""% ---------------------------------------------------------------------------------------------
% p-Laplacian tables (agent E).  Requires booktabs.  Generated by experiments/plap/make_tex.py.
% Corrected loss  \int(\Delta_p u+E|u|^{p-2}u)^2 + \mu(\int|u|^p-1)^2,  \mu=200, 3x128 tanh, N=5000,
% Adam with cosine lr decay 1e-3 -> 1e-5, 1500 epochs per value of E.
% E_PINN = minimiser in E of the residual of the network trained at the grid minimum (the "refinement" step);
% E_curve = vertex of the parabola through the three lowest points of the coarse loss curve.
% ---------------------------------------------------------------------------------------------
""")
def modes(dom, caption, label, hc):
    rows = [e for e in S["main"] if e["dom"] == dom]
    t = [r"\begin{table}[ht]", r"\centering", r"\begin{tabular}{clccccc}", r"\toprule",
         r"$k$ & Symmetry of the eigenfunction [reference] & $E_{\rm ref}$ & $E_{\rm PINN}$ & rel.\ err.\ (\%) & $E_{\rm curve}$ ($h=HC$) & $\bar\Lambda_p^{1/2}$ \\".replace("HC", hc),
         r"\midrule"]
    for e in rows:
        t.append(f"{e['k']} & {SYM.get(e['ref_type'], e['ref_type'])} & {e['ref']:.4f} & {e['E_ls']:.4f} & {pc(e['err_E_ls'])} & "
                 f"{e['coarse_vertex']:.2f} ({pc(e['err_coarse_vertex'])}) & {e['r_min']:.2f} \\\\")
    t += [r"\bottomrule", r"\end{tabular}", r"\caption{%s}" % caption, r"\label{%s}" % label, r"\end{table}", ""]
    return t
out += modes("disk", r"Eigenvalues of the $p$-Laplacian, $p=2.2$, in the unit disk detected in the window $E\in[3,58]$ "
             r"(all local minima of the loss curve). References: radial shooting and $P_1$ finite elements on the nodal domain "
             r"(first eigenvalue of the sector, extended by odd reflection). The relative error of $E_{\rm curve}$ is in parentheses.",
             "tab.plap.disk", "1")
out += modes("square", r"Eigenvalues of the $p$-Laplacian, $p=2.2$, in the square $[0,2]^2$ detected in the window $E\in[3,37]$. "
             r"References: $P_1$ finite elements on the nodal domain and scaling.", "tab.plap.square", "1")
out += modes("ball3", r"Eigenvalues of the $p$-Laplacian, $p=2.5$, in the unit ball of $\mathbb R^3$ detected in the window $E\in[8,46]$.",
             "tab.plap.ball", "2")
# convergence
t = [r"\begin{table}[ht]", r"\centering", r"\begin{tabular}{lcccccc}", r"\toprule",
     r"Setting & $\bar\Lambda_p(6.0)$ & $\bar\Lambda_p(6.5)$ & $\bar\Lambda_p(7.0)$ & $E_{\rm curve}$ (err.\ \%) & $E_{\rm PINN}$ (err.\ \%) & time (min) \\", r"\midrule"]
for e in S["convergence"]:
    L = dict(zip(e["E"], e["Lam_all"])); g = lambda x: f"{L[x]:.3f}" if x in L else "--"
    d = e["desc"].replace("mu=", r"$\mu=$").replace("2x", r"$2\times$").replace("4x", r"$4\times$") if e["name"] != "conv_base_s0" else r"baseline: $3\times128$, $N=5000$, 1500 epochs, lr decay, $\mu=200$, $h=0.5$"
    if "E-step" in e["desc"]: d = "$E$-step $h=" + e["desc"].split("=")[1] + "$"
    t.append(f"{d} & {g(6.0)} & {e['Lam_65']:.3f} & {g(7.0)} & {e['E_vertex']:.3f} ({pc(e['err_vertex'])}) & {e['E_ls']:.4f} ({pc(e['err_ls'])}) & {e['wall_s']/60:.0f} \\\\")
t += [r"\bottomrule", r"\end{tabular}",
      r"\caption{Convergence study for the first eigenvalue of the $p$-Laplacian, $p=2.2$, in the unit disk ($E_1=E1REF$ by radial shooting). "
      r"Each row changes one setting of the baseline; the loss curve is sampled at $E=6.0,6.5,7.0$ (fresh sample of $4\cdot10^4$ points). "
      r"P0 is the protocol of the previous version (constant learning rate $10^{-3}$, early stopping).}".replace("E1REF", "%.5f" % S["refs"]["disk22_E1"]),
      r"\label{tab.plap.conv}", r"\end{table}", ""]
out += t
# other p
t = [r"\begin{table}[ht]", r"\centering", r"\begin{tabular}{cccccc}", r"\toprule",
     r"$p$ & $E_1$ (shooting) & $E_{\rm PINN}$ & rel.\ err.\ (\%) & $E_{\rm curve}$ (err.\ \%) & $\bar\Lambda_p^{1/2}$ \\", r"\midrule"]
for e in S["other_p"]:
    nm = "" if e["name"] != "disk_p4_w256d4" else r" ($4\times256$)"
    t.append(f"{e['p']}{nm} & {e['ref']:.4f} & {e['E_ls']:.4f} & {pc(e['err_E_ls'])} & {e['E_vertex']:.3f} ({pc(e['err_E_vertex'])}) & {e['r_min']:.2f} \\\\")
t += [r"\bottomrule", r"\end{tabular}", r"\caption{First eigenvalue of the $p$-Laplacian in the unit disk for several $p$ (baseline settings).}",
      r"\label{tab.plap.p}", r"\end{table}", ""]
out += t
# radial references
t = [r"\begin{table}[ht]", r"\centering", r"\begin{tabular}{ccccccc}", r"\toprule", r"$p$ & 1.5 & 2 & 2.2 & 2.5 & 3 & 4 \\", r"\midrule"]
for d in (2, 3):
    t.append(f"$E_1(B_1)$, $d={d}$ & " + " & ".join(f"{refs[f'p{p}_d{d}']['E1']:.4f}" for p in (1.5, 2.0, 2.2, 2.5, 3.0, 4.0)) + r" \\")
t += [r"\bottomrule", r"\end{tabular}", r"\caption{First eigenvalue of the $p$-Laplacian in the unit ball of $\mathbb R^d$ computed by shooting for the radial equation.}",
      r"\label{tab.plap.ref}", r"\end{table}", ""]
out += t
# legacy
t = [r"% Legacy loss (E u instead of E|u|^{p-2}u, mean(u^2)=1) -- for the response letter", r"% run | grid min | vertex | E_ls | published | true"]
for e in S["paper_protocol_and_legacy"]:
    t.append(f"% {e['label']} | {e['E_grid']:.2f} | {e['E_vertex']:.3f} | {e['E_ls']:.4f} | {e.get('published','--')} | {e['nearest_ref']:.4f}")
out += t
open(HERE / "tables.tex", "w").write("\n".join(out) + "\n")
print("wrote tables.tex")
